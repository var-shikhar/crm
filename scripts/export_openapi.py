#!/usr/bin/env python3
"""Export each service's OpenAPI document and a one-page endpoint index.

Reads from the running stack (./scripts/run-local.sh start):
    python scripts/export_openapi.py
Writes docs/openapi/<service>.json and docs/API_ENDPOINTS.md.
"""

import json
import os
import re
import urllib.request
from pathlib import Path

BASE = os.environ.get("BASE_URL", "http://127.0.0.1:8080")
DOCS = Path(__file__).resolve().parent.parent / "docs"
SERVICES = [("auth-service", "/auth"), ("customer-service", "/crm"), ("audit-service", "/audit")]
INTERNAL = ("/api/v1/authz/", "/oauth/introspect", "/api/v1/events/batch")

# Permissions enforced by the auth service's own endpoints (declared in code via require("...")).
AUTH_PERMISSIONS = {
    ("GET", "/api/v1/users"): "user:read", ("GET", "/api/v1/users/{user_id}"): "user:read",
    ("GET", "/api/v1/roles"): "role:read", ("GET", "/api/v1/permissions"): "role:read",
}


def access(service: str, method: str, path: str, op: dict) -> str:
    text = op.get("description", "")
    found = re.findall(r"Requires `([a-z:_]+)`", text)
    if found:
        return f"`{found[0]}`"
    if service == "auth-service":
        if path.startswith(INTERNAL):
            return "service client (HTTP Basic)"
        if path.startswith("/api/v1/me"):
            return "any signed-in user"
        if path.startswith("/api/v1/users"):
            return f"`{AUTH_PERMISSIONS.get((method, path), 'user:manage')}`"
        if path.startswith(("/api/v1/roles", "/api/v1/permissions")):
            return f"`{AUTH_PERMISSIONS.get((method, path), 'role:manage')}`"
        if path.startswith("/oauth"):
            return "OAuth client"
        return "public"
    if service == "audit-service":
        return "`audit:write` (service clients only)" if path.endswith("/batch") else "`audit:read`"
    return "bearer token"


def main() -> None:
    (DOCS / "openapi").mkdir(parents=True, exist_ok=True)
    out = ["# API endpoint index", "",
           "Generated by `scripts/export_openapi.py` from the running services. Do not edit by hand.",
           "Full request and response schemas are in `docs/openapi/*.json` and, live, at `/<prefix>/docs`.", ""]
    for service, prefix in SERVICES:
        with urllib.request.urlopen(f"{BASE}{prefix}/openapi.json", timeout=10) as resp:
            spec = json.load(resp)
        (DOCS / "openapi" / f"{service}.json").write_text(json.dumps(spec, indent=2) + "\n")
        out += [f"## {spec['info']['title']} (gateway prefix `{prefix}`)", "",
                "| Method | Path | Purpose | Access | Exposed by gateway |", "|---|---|---|---|---|"]
        for path, ops in spec["paths"].items():
            for method, op in ops.items():
                exposed = "no (internal)" if (prefix + path).startswith(
                    tuple(("/auth" if i != INTERNAL[2] else "/audit") + i for i in INTERNAL)) else "yes"
                out.append(f"| {method.upper()} | `{path}` | {op.get('summary', '')} | "
                           f"{access(service, method.upper(), path, op)} | {exposed} |")
        out.append("")
    (DOCS / "API_ENDPOINTS.md").write_text("\n".join(out))
    print("wrote docs/openapi/*.json and docs/API_ENDPOINTS.md")


if __name__ == "__main__":
    main()
